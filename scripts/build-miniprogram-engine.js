// Generate the WeChat Mini Program CommonJS build of the simulation engine.
// Usage: node scripts/build-miniprogram-engine.js
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'public', 'js', 'simulate.js');
const OUT = path.join(ROOT, 'miniprogram', 'utils', 'simulate.js');

const source = await fs.readFile(SRC, 'utf8');
const body = source.replace(/^export function /gm, 'function ');
const output = `// AUTO-GENERATED from public/js/simulate.js by scripts/build-miniprogram-engine.js\n// Do not edit this file directly.\n\n${body}\nmodule.exports = {\n  parseDate,\n  formatDate,\n  buildAnchors,\n  holdingPeriodTaxRate,\n  simulate,\n  xirr,\n  summarizeByYear,\n};\n`;

await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(OUT, output);
console.log(`generated ${path.relative(ROOT, OUT)}`);
